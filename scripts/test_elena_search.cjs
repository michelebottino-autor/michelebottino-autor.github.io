'use strict';
const assert=require('node:assert/strict');
const engine=require('../adc/assets/elena-dialogo.js');
const index=require('../adc/assets/elena-indice.json');
const approved=require('../adc/assets/elena-risposte-approvate.json').answers;
const kb=require('../adc/assets/elena-conoscenza-verificata.json');
const r=q=>engine.rank(q,index.entries);
const ask=q=>engine.reply(q,index,approved,kb);
let n=0;const t=(label,fn)=>{fn();console.log('PASS',label);n++};
t('chiesa annunziata',()=>assert.ok(r("Chiesa dell'Annunziata a Calatabiano").some(x=>x.url==='/adc/chiese/')));
t('madonna del carmine phrase',()=>assert.equal(r('Madonna del Carmine a Calatabiano')[0].url,'/adc/monasteri/carmelitani-calatabiano/'));
t('frati minori gesu maria',()=>assert.equal(r('Frati Minori Gesù e Maria')[0].url,'/adc/monasteri/frati-minori-gesu-e-maria/'));
t('greek acts and 1103',()=>assert.equal(r('San Giovanni di Fiumefreddo 1103')[0].url,'/adc/monasteri/san-giovanni-fiumefreddo/'));
t('1213 castle',()=>assert.ok(r('Castello 1213')[0].url.includes('1213')));
t('regional source alias',()=>assert.ok(r('Mulino Alcantara').some(x=>x.url.includes('acque-mulini'))));
t('unrelated text no false result',()=>assert.deepEqual(r('astronave terraformazione'),[]));
t('empty query',()=>assert.deepEqual(r(''),[]));
t('malformed index entries ignored',()=>assert.deepEqual(engine.rank('castello',null),[]));
t('unsafe external URL filtered',()=>assert.deepEqual(engine.rank('castello',[{url:'https://evil.example/',title:'Castello',tags:['castello']}]),[]));
t('followup retains subject',()=>assert.match(engine.contextualQuery('E le fonti?','Castello Calatabiano 1213'),/castello/));
t('approved historical reply unchanged',()=>assert.equal(ask('Chi possedeva il castello di Calatabiano nel 1213?').kind,'documentary'));
t('no invented answer',()=>assert.notEqual(ask('astronave terraformazione').kind,'documentary'));
t('source response labels as links only',()=>assert.equal(ask('Madonna del Carmine').kind,'index'));
t('results are limited',()=>assert.ok(r('chiesa').length<=5));
t('results deduplicated',()=>{const arr=r('chiesa');assert.equal(new Set(arr.map(x=>x.url)).size,arr.length)});
console.log('ELENA_SEARCH_TESTS',n);
